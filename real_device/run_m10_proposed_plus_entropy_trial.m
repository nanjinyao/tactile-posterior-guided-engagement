function result = run_m10_proposed_plus_entropy_trial()
%RUN_M10_PROPOSED_PLUS_ENTROPY_TRIAL One fixed M10 Proposed+ demo pilot.
%
% This is the final M10-only companion to the already completed M12 demo.
% Install the M10 peg, place its upright unloaded tip a little above the
% freshly taught M10 hole centre, align the fixture X/Y and peg yaw exactly as
% in the completed M10 sampling campaign, then run this file.  The launcher
% makes one lateral air move to a fixed point on the 3.75 degree sampling ray
% and immediately runs:
%
%   Proposed+ learned posterior + residual entropy search
%
% There is no menu, automatic retry, M12 motion, or absolute historical WORLD
% target.  A failed attempt stops at the measured current state and must be
% recovered manually before this same file is run again.  At most three
% separately invoked attempts are allowed by this pilot checkpoint.
%
% The selected point is r=4.600 mm, 0.933 mm inward from the twice-completed
% real M10 A003p75 sampling location.  It preserves the sampled ray while
% adding 0.942 mm worst-case socket-head support margin after the 0.25 mm
% touchdown lock bound.  The 4.8 mm residual action disk retains 0.585 mm
% conservative capture margin.  This is an in-sample-adjacent fixed demo, not
% general M10 promotion, random evaluation, or success-rate evidence.

realDir = fileparts(mfilename('fullpath'));
dataDir = fullfile(realDir, 'data');
if ~isfolder(dataDir)
    [made, message] = mkdir(dataDir);
    assert(made, 'M10Demo:DataDirectory', ...
        'Cannot create %s: %s', dataDir, message);
end

executionMode = 'FULL_LOOP_PROPOSED_PLUS_LEARNED_ENTROPY_M10';
controllerTuningRevision = ...
    'M10_CHAMFER_FORCE14_TERMINAL_TORQUE010_V2';
priorSuccessfulControllerRevision = ...
    'SHARED_INSERTION_BASELINE_V1';
campaignPath = fullfile(dataDir, ...
    'm10_proposed_plus_fixed_demo_campaign_v1.json');
pilotPath = fullfile(realDir, 'configs', ...
    'm10_fixed_demo_pilot_authorization_v1.json');
pilotSha256 = ...
    '8f09bdc86949ee448d29795ca7100347be4b865083f93dfa7761eae9834dc825';
pilotAuthorizationId = ...
    'M10_FIXED_PROPOSED_PLUS_DEMO_20260730_V1';
assert(isfile(pilotPath) && ...
        strcmp(m10DemoSha256File(pilotPath), pilotSha256), ...
    'M10Demo:PilotTrustAnchor', ...
    'The fixed M10 pilot authorization is missing or changed.');

demoOffsetFixtureMm = [ ...
    4.590151046897575, 0.3008543944586581];
demoRadiusMm = 4.600;
demoAngleFixtureDeg = 3.750;
sourceSampleId = ...
    'M10-CLEAN_CANDIDATE-SUPPORTED-A003p75';
sourceSampleOffsetFixtureMm = [5.521449100, 0.361894894];
sourceSampleRadiusMm = 5.533296312;
residualActionReachMm = 4.800;
conservativeCaptureRadiusMm = 0.635;
touchdownXyLockBoundMm = 0.250;
headRadiusMm = 18.975 / 2.0;
tipCircumradiusMm = 6.4 / sqrt(3.0);
maximumPhysicalTipCenterRadiusMm = headRadiusMm - tipCircumradiusMm;
supportEnvelopeAllowanceMm = 0.600;
maximumCommandedTipCenterRadiusMm = ...
    maximumPhysicalTipCenterRadiusMm - supportEnvelopeAllowanceMm;
worstCaseResidualCaptureMarginMm = ...
    conservativeCaptureRadiusMm - ...
    (demoRadiusMm + touchdownXyLockBoundMm - residualActionReachMm);
headSupportMarginMm = headRadiusMm - ...
    (demoRadiusMm + touchdownXyLockBoundMm + tipCircumradiusMm);
assert(norm(demoOffsetFixtureMm - demoRadiusMm * [ ...
        cosd(demoAngleFixtureDeg), sind(demoAngleFixtureDeg)]) <= 1e-12 && ...
        worstCaseResidualCaptureMarginMm > 0.0 && ...
        headSupportMarginMm > 0.0 && ...
        abs(maximumPhysicalTipCenterRadiusMm - ...
            5.792458277186394) <= 1e-12 && ...
        abs(maximumCommandedTipCenterRadiusMm - ...
            5.192458277186394) <= 1e-12, ...
    'M10Demo:FixedGeometry', ...
    'The fixed M10 demo geometry no longer satisfies its reach/support bounds.');

maximumLauncherAttempts = 3;
if isfile(campaignPath)
    campaign = jsondecode(fileread(campaignPath));
    validateM10DemoCampaign(campaign, executionMode, ...
        demoOffsetFixtureMm, sourceSampleId, pilotAuthorizationId, ...
        maximumLauncherAttempts);
else
    campaign = struct( ...
        'schema', 'M10_PROPOSED_PLUS_FIXED_DEMO_CAMPAIGN_V1', ...
        'campaign_id', ['M10_PROPOSED_PLUS_DEMO_', ...
            char(datetime('now', 'Format', 'yyyyMMdd_HHmmss_SSS'))], ...
        'status', 'READY', ...
        'created_local', m10DemoIsoTimestamp(), ...
        'updated_local', m10DemoIsoTimestamp(), ...
        'method_mode', executionMode, ...
        'demo_design_id', ...
            'M10_FIXED_PROPOSED_PLUS_NEAR_A003P75_R4P600_V1', ...
        'demo_seed_token', 'M10_DEMO_20260730_A003P75_INWARD', ...
        'source_sample_id', sourceSampleId, ...
        'source_sample_offset_fixture_mm', sourceSampleOffsetFixtureMm, ...
        'source_sample_radius_mm', sourceSampleRadiusMm, ...
        'demo_offset_fixture_mm', demoOffsetFixtureMm, ...
        'demo_radius_mm', demoRadiusMm, ...
        'demo_angle_fixture_deg', demoAngleFixtureDeg, ...
        'residual_action_reach_mm', residualActionReachMm, ...
        'conservative_capture_radius_mm', ...
            conservativeCaptureRadiusMm, ...
        'touchdown_xy_lock_bound_mm', touchdownXyLockBoundMm, ...
        'worst_case_residual_capture_margin_mm', ...
            worstCaseResidualCaptureMarginMm, ...
        'head_support_margin_after_touchdown_lock_mm', ...
            headSupportMarginMm, ...
        'fresh_center_support_envelope_safety_only', true, ...
        'support_envelope_posterior_input', false, ...
        'support_envelope_target_ranking_input', false, ...
        'support_envelope_steering_input', false, ...
        'maximum_physical_tip_center_radius_from_fresh_center_mm', ...
            maximumPhysicalTipCenterRadiusMm, ...
        'support_envelope_allowance_mm', supportEnvelopeAllowanceMm, ...
        'maximum_commanded_tip_center_radius_from_fresh_center_mm', ...
            maximumCommandedTipCenterRadiusMm, ...
        'pilot_authorization_id', pilotAuthorizationId, ...
        'pilot_authorization_path', pilotPath, ...
        'pilot_authorization_sha256', pilotSha256, ...
        'maximum_launcher_attempts', maximumLauncherAttempts, ...
        'attempt_count', 0, ...
        'attempt_records', m10DemoEmptyAttemptRecords(), ...
        'controller_tuning_revision', controllerTuningRevision, ...
        'current_public_trial_token', '', ...
        'last_started_local', '', ...
        'last_finished_local', '', ...
        'run_directory', '', ...
        'outcome_kind', 'NOT_RUN', ...
        'last_error_identifier', '', ...
        'last_error_message', '', ...
        'claim_boundary', ...
            ['FIXED_IN_SAMPLE_ADJACENT_M10_DEMO_ONLY_NOT_GENERAL_', ...
             'PROMOTION_NOT_RANDOM_NOT_SUCCESS_RATE_EVIDENCE']);
    writeM10DemoCheckpoint(campaignPath, campaign);
end

attemptRecords = m10DemoCampaignAttemptRecords( ...
    campaign, priorSuccessfulControllerRevision);
tuningRevisionAlreadyAttempted = ~isempty(attemptRecords) && ...
    any(strcmp(string({attemptRecords.controller_tuning_revision}), ...
        string(controllerTuningRevision)));
if strcmp(char(campaign.status), 'COMPLETE')
    assert(~tuningRevisionAlreadyAttempted && ...
            double(campaign.attempt_count) == 1, ...
        'M10Demo:TuningValidationAlreadyComplete', ...
        ['The M10 force/terminal tuning revision was already attempted, ', ...
         'or the completed source campaign is not the single successful ', ...
         'untuned run.  Do not add another unplanned repeat.']);
    campaign.status = 'TUNING_VALIDATION_READY';
    campaign.controller_tuning_revision = controllerTuningRevision;
    campaign.tuning_validation_source_controller_revision = ...
        priorSuccessfulControllerRevision;
    campaign.tuning_validation_source_attempt_index = ...
        double(campaign.attempt_count);
    campaign.tuning_validation_source_run_directory = ...
        char(campaign.run_directory);
    campaign.tuning_validation_authorized_local = ...
        m10DemoIsoTimestamp();
    campaign.attempt_records = attemptRecords;
    writeM10DemoCheckpoint(campaignPath, campaign);
end
assert(~strcmp(char(campaign.status), 'RUNNING'), ...
    'M10Demo:PreviousAttemptStillRunning', ...
    ['The campaign still marks a prior MATLAB invocation RUNNING.  ', ...
     'Do not create a second possible command owner; inspect and close ', ...
     'that invocation before retrying.']);
assert(double(campaign.attempt_count) < maximumLauncherAttempts, ...
    'M10Demo:AttemptLimit', ...
    ['The three separately invoked fixed-demo attempts are exhausted.  ', ...
     'Do not widen or reset this pilot silently.']);

publicTrialToken = char(java.util.UUID.randomUUID());
upcomingAttempt = double(campaign.attempt_count) + 1;
privateTrialSpec = struct( ...
    'schema', 'M10_PROPOSED_PLUS_FIXED_DEMO_PRIVATE_TRIAL_V1', ...
    'campaign_id', char(campaign.campaign_id), ...
    'trial_index', upcomingAttempt, ...
    'offset_index', 1, ...
    'offset_fixture_mm', demoOffsetFixtureMm, ...
    'method_index', 1, ...
    'method_mode', executionMode, ...
    'order_position', 1, ...
    'public_trial_token', publicTrialToken, ...
    'campaign_center_world_xy_mm', [], ...
    'public_entrypoint', 'run_m10_proposed_plus_entropy_trial', ...
    'truth_firewall', ...
        'OFFSET_USED_ONLY_FOR_PRE_TOUCHDOWN_AIR_TRANSPORT_NOT_POLICY_INPUT', ...
    'demo_design_id', ...
        'M10_FIXED_PROPOSED_PLUS_NEAR_A003P75_R4P600_V1', ...
    'demo_seed_token', 'M10_DEMO_20260730_A003P75_INWARD', ...
    'source_sample_id', sourceSampleId, ...
    'source_sample_offset_fixture_mm', sourceSampleOffsetFixtureMm, ...
    'offset_selection_rationale', ...
        ['INWARD_SAME_RAY_NEAR_TWICE_COMPLETED_REAL_M10_SAMPLE_', ...
         'FOR_HEAD_SUPPORT_AND_FINITE_RESIDUAL_REACH'], ...
    'pilot_authorization_id', pilotAuthorizationId, ...
    'controller_tuning_revision', controllerTuningRevision);

campaign.status = 'RUNNING';
campaign.attempt_count = upcomingAttempt;
campaign.controller_tuning_revision = controllerTuningRevision;
campaign.current_public_trial_token = publicTrialToken;
campaign.last_started_local = m10DemoIsoTimestamp();
campaign.last_finished_local = '';
campaign.run_directory = '';
campaign.outcome_kind = 'RUNNING';
campaign.last_error_identifier = '';
campaign.last_error_message = '';
attemptRecords = m10DemoCampaignAttemptRecords( ...
    campaign, priorSuccessfulControllerRevision);
attemptRecords(end + 1) = m10DemoNewAttemptRecord( ...
    upcomingAttempt, publicTrialToken, campaign.last_started_local, ...
    controllerTuningRevision);
campaign.attempt_records = attemptRecords;
writeM10DemoCheckpoint(campaignPath, campaign);

fprintf(['\nM10 fixed Proposed+ demo attempt %d/%d: ', ...
    'r %.3f mm at %.3f deg near %s.\n', ...
    'Fresh taught M10 centre required; live preflight and motion begin now.\n'], ...
    double(campaign.attempt_count), maximumLauncherAttempts, ...
    demoRadiusMm, demoAngleFixtureDeg, sourceSampleId);

clear execute_m12_contact_engagement_policy
try
    result = execute_m12_contact_engagement_policy( ...
        executionMode, privateTrialSpec);
    taskComplete = isfield(result, 'method_execution_completed') && ...
        logical(result.method_execution_completed) && ...
        isfield(result, 'capture_found') && logical(result.capture_found) && ...
        isfield(result, 'completion_status') && ...
        startsWith(string(result.completion_status), "TASK_COMPLETE_");
    assert(taskComplete, 'M10Demo:NoTaskCompletion', ...
        ['The M10 engine returned without the required capture and complete ', ...
         'terminal event chain.']);
catch trialError
    campaign = jsondecode(fileread(campaignPath));
    [failedRunDirectory, failureEvidence] = ...
        m10DemoFindRunEvidence(dataDir, publicTrialToken);
    campaign.status = 'RETRY_PENDING';
    campaign.last_finished_local = m10DemoIsoTimestamp();
    campaign.run_directory = failedRunDirectory;
    campaign.outcome_kind = ...
        'HARD_STATE_IMPLEMENTATION_OR_NO_TASK_COMPLETION';
    campaign.last_error_identifier = char(trialError.identifier);
    campaign.last_error_message = m10DemoOneLine(trialError.message);
    attemptRecords = m10DemoCampaignAttemptRecords( ...
        campaign, priorSuccessfulControllerRevision);
    recordIndex = m10DemoAttemptRecordIndex( ...
        attemptRecords, publicTrialToken);
    attemptRecords(recordIndex).finished_local = ...
        campaign.last_finished_local;
    attemptRecords(recordIndex).status = 'RETRY_PENDING';
    attemptRecords(recordIndex).run_directory = failedRunDirectory;
    attemptRecords(recordIndex).outcome_kind = campaign.outcome_kind;
    attemptRecords(recordIndex).error_identifier = ...
        campaign.last_error_identifier;
    attemptRecords(recordIndex).error_message = ...
        campaign.last_error_message;
    attemptRecords(recordIndex).motion_attempted = ...
        failureEvidence.motion_attempted;
    attemptRecords(recordIndex).motion_commanded = ...
        failureEvidence.motion_commanded;
    attemptRecords(recordIndex).method_execution_completed = ...
        failureEvidence.method_execution_completed;
    attemptRecords(recordIndex).capture_found = ...
        failureEvidence.capture_found;
    attemptRecords(recordIndex).completion_status = ...
        failureEvidence.completion_status;
    campaign.attempt_records = attemptRecords;
    writeM10DemoCheckpoint(campaignPath, campaign);
    rethrow(trialError);
end

campaign = jsondecode(fileread(campaignPath));
campaign.status = 'COMPLETE';
campaign.last_finished_local = m10DemoIsoTimestamp();
campaign.run_directory = char(result.run_directory);
campaign.outcome_kind = 'TASK_SUCCESS';
campaign.last_error_identifier = '';
campaign.last_error_message = '';
attemptRecords = m10DemoCampaignAttemptRecords( ...
    campaign, priorSuccessfulControllerRevision);
recordIndex = m10DemoAttemptRecordIndex( ...
    attemptRecords, publicTrialToken);
attemptRecords(recordIndex).finished_local = ...
    campaign.last_finished_local;
attemptRecords(recordIndex).status = 'COMPLETE';
attemptRecords(recordIndex).run_directory = char(result.run_directory);
attemptRecords(recordIndex).outcome_kind = 'TASK_SUCCESS';
attemptRecords(recordIndex).error_identifier = '';
attemptRecords(recordIndex).error_message = '';
attemptRecords(recordIndex).motion_attempted = ...
    m10DemoLogicalField(result, 'motion_attempted', false);
attemptRecords(recordIndex).motion_commanded = ...
    m10DemoLogicalField(result, 'motion_commanded', false);
attemptRecords(recordIndex).method_execution_completed = ...
    m10DemoLogicalField(result, 'method_execution_completed', false);
attemptRecords(recordIndex).capture_found = ...
    m10DemoLogicalField(result, 'capture_found', false);
attemptRecords(recordIndex).completion_status = ...
    m10DemoTextField(result, 'completion_status', '');
campaign.attempt_records = attemptRecords;
writeM10DemoCheckpoint(campaignPath, campaign);

result.m10_fixed_demo_campaign_id = char(campaign.campaign_id);
result.m10_fixed_demo_campaign_path = campaignPath;
result.m10_fixed_demo_attempt_count = double(campaign.attempt_count);
result.m10_fixed_demo_attempt_records = campaign.attempt_records;
result.m10_fixed_demo_offset_fixture_mm = demoOffsetFixtureMm;
result.m10_fixed_demo_source_sample_id = sourceSampleId;
result.m10_fixed_demo_pilot_authorization_id = pilotAuthorizationId;
result.m10_fixed_demo_controller_tuning_revision = ...
    controllerTuningRevision;
result.m10_fixed_demo_outcome_kind = 'TASK_SUCCESS';
end

function validateM10DemoCampaign( ...
        campaign, executionMode, demoOffsetFixtureMm, ...
        sourceSampleId, pilotAuthorizationId, maximumLauncherAttempts)
assert(isstruct(campaign) && ...
        strcmp(char(campaign.schema), ...
            'M10_PROPOSED_PLUS_FIXED_DEMO_CAMPAIGN_V1') && ...
        strcmp(char(campaign.method_mode), executionMode) && ...
        norm(double(reshape( ...
            campaign.demo_offset_fixture_mm, 1, [])) - ...
            demoOffsetFixtureMm) <= 1e-12 && ...
        strcmp(char(campaign.source_sample_id), sourceSampleId) && ...
        strcmp(char(campaign.pilot_authorization_id), ...
            pilotAuthorizationId) && ...
        double(campaign.maximum_launcher_attempts) == ...
            maximumLauncherAttempts && ...
        double(campaign.attempt_count) >= 0 && ...
        double(campaign.attempt_count) <= maximumLauncherAttempts && ...
        double(campaign.attempt_count) == ...
            round(double(campaign.attempt_count)) && ...
        logical(campaign. ...
            fresh_center_support_envelope_safety_only) && ...
        ~logical(campaign.support_envelope_posterior_input) && ...
        ~logical(campaign.support_envelope_target_ranking_input) && ...
        ~logical(campaign.support_envelope_steering_input) && ...
        abs(double(campaign. ...
            maximum_physical_tip_center_radius_from_fresh_center_mm) - ...
            5.792458277186394) <= 1e-12 && ...
        abs(double(campaign.support_envelope_allowance_mm) - 0.600) <= ...
            1e-12 && ...
        abs(double(campaign. ...
            maximum_commanded_tip_center_radius_from_fresh_center_mm) - ...
            5.192458277186394) <= 1e-12 && ...
        contains(string(campaign.claim_boundary), ...
            "NOT_GENERAL_PROMOTION"), ...
    'M10Demo:CampaignDrift', ...
    'The persisted fixed M10 demo identity, geometry, or scope changed.');
attemptRecords = m10DemoCampaignAttemptRecords( ...
    campaign, 'SHARED_INSERTION_BASELINE_V1');
attemptCount = double(campaign.attempt_count);
assert(numel(attemptRecords) == attemptCount && ...
        (attemptCount == 0 || ...
            isequal([attemptRecords.attempt_index], 1:attemptCount)) && ...
        (attemptCount == 0 || ...
            numel(unique(string( ...
                {attemptRecords.public_trial_token}))) == attemptCount) && ...
        (attemptCount == 0 || all(ismember(string( ...
            {attemptRecords.controller_tuning_revision}), [ ...
                "SHARED_INSERTION_BASELINE_V1", ...
                "M10_CHAMFER_FORCE14_TERMINAL_TORQUE010_V2"]))), ...
    'M10Demo:CampaignAttemptHistory', ...
    ['The fixed M10 demo must retain one ordered, unique audit record for ', ...
     'every separately invoked attempt.']);
end

