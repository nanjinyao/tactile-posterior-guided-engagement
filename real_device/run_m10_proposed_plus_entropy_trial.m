function records = m10DemoCampaignAttemptRecords( ...
        campaign, legacyControllerTuningRevision)
records = m10DemoEmptyAttemptRecords();
if ~isfield(campaign, 'attempt_records') || ...
        isempty(campaign.attempt_records)
    return;
end
assert(isstruct(campaign.attempt_records), ...
    'M10Demo:CampaignAttemptHistoryType', ...
    'Persisted M10 attempt_records must be a JSON object array.');
records = reshape(campaign.attempt_records, 1, []);
if ~isfield(records, 'controller_tuning_revision')
    for recordIndex = 1:numel(records)
        records(recordIndex).controller_tuning_revision = ...
            char(legacyControllerTuningRevision);
    end
end
required = fieldnames(m10DemoNewAttemptRecord( ...
    1, 'TOKEN', 'TIME', 'REVISION'));
assert(all(isfield(records, required)), ...
    'M10Demo:CampaignAttemptHistoryFields', ...
    'One or more persisted M10 attempt records are incomplete.');
end

function index = m10DemoAttemptRecordIndex(records, publicTrialToken)
matches = arrayfun(@(record) strcmp( ...
    char(record.public_trial_token), char(publicTrialToken)), records);
index = find(matches, 1, 'last');
assert(~isempty(index) && sum(matches) == 1, ...
    'M10Demo:CampaignAttemptToken', ...
    'The current M10 public trial token is absent or duplicated.');
end

function [runDirectory, evidence] = ...
        m10DemoFindRunEvidence(dataDir, publicTrialToken)
runDirectory = '';
evidence = struct( ...
    'motion_attempted', false, ...
    'motion_commanded', false, ...
    'method_execution_completed', false, ...
    'capture_found', false, ...
    'completion_status', 'SUMMARY_NOT_FOUND');
entries = dir(fullfile(dataDir, ...
    'M10_proposed_plus_entropy_grid_*'));
if isempty(entries)
    return;
end
[~, order] = sort([entries.datenum], 'descend');
entries = entries(order);
for entryIndex = 1:numel(entries)
    if ~entries(entryIndex).isdir
        continue;
    end
    candidateDirectory = fullfile(dataDir, entries(entryIndex).name);
    manifestPath = fullfile(candidateDirectory, 'manifest.json');
    if ~isfile(manifestPath)
        continue;
    end
    try
        manifest = jsondecode(fileread(manifestPath));
    catch
        continue;
    end
    if ~isfield(manifest, 'paired_trial_public_token') || ...
            ~strcmp(char(manifest.paired_trial_public_token), ...
                char(publicTrialToken))
        continue;
    end
    runDirectory = candidateDirectory;
    summaryPath = fullfile(candidateDirectory, 'summary.json');
    if isfile(summaryPath)
        try
            summary = jsondecode(fileread(summaryPath));
            evidence.motion_attempted = ...
                m10DemoLogicalField(summary, 'motion_attempted', false);
            evidence.motion_commanded = ...
                m10DemoLogicalField(summary, 'motion_commanded', false);
            evidence.method_execution_completed = ...
                m10DemoLogicalField( ...
                    summary, 'method_execution_completed', false);
            evidence.capture_found = ...
                m10DemoLogicalField(summary, 'capture_found', false);
            evidence.completion_status = ...
                m10DemoTextField( ...
                    summary, 'completion_status', 'SUMMARY_INCOMPLETE');
        catch
            evidence.completion_status = 'SUMMARY_UNREADABLE';
        end
    end
    return;
end
end

function value = m10DemoLogicalField(record, fieldName, defaultValue)
value = logical(defaultValue);
if isstruct(record) && isfield(record, fieldName) && ...
        ~isempty(record.(fieldName))
    value = logical(record.(fieldName));
end
end

function value = m10DemoTextField(record, fieldName, defaultValue)
value = char(defaultValue);
if isstruct(record) && isfield(record, fieldName) && ...
        ~isempty(record.(fieldName))
    value = char(string(record.(fieldName)));
end
end

function writeM10DemoCheckpoint(path, campaign)
campaign.updated_local = m10DemoIsoTimestamp();
encoded = [jsonencode(campaign, 'PrettyPrint', true), newline];
temporaryPath = [tempname(fileparts(path)), '.tmp'];
fileId = fopen(temporaryPath, 'w');
assert(fileId >= 0, 'M10Demo:CheckpointWrite', ...
    'Cannot open a temporary M10 demo checkpoint.');
closer = onCleanup(@() fclose(fileId));
fwrite(fileId, encoded, 'char');
clear closer;
[moved, message] = movefile(temporaryPath, path, 'f');
assert(moved, 'M10Demo:CheckpointCommit', ...
    'Cannot atomically replace %s: %s', path, message);
end

function digest = m10DemoSha256File(path)
assert(~isempty(regexp(path, '^[A-Za-z0-9_./-]+$', 'once')), ...
    'M10Demo:HashPath', 'Unsupported hash path: %s', path);
[status, output] = system(['/usr/bin/sha256sum ', path]);
assert(status == 0, 'M10Demo:Hash', ...
    'sha256sum failed for %s.', path);
tokens = regexp(output, '^([0-9a-fA-F]{64})', 'tokens', 'once');
assert(~isempty(tokens), 'M10Demo:Hash', ...
    'Unexpected sha256sum output for %s.', path);
digest = lower(tokens{1});
end

function value = m10DemoIsoTimestamp()
value = char(datetime('now', 'TimeZone', 'local', ...
    'Format', 'yyyy-MM-dd''T''HH:mm:ss.SSSXXX'));
end

function value = m10DemoOneLine(value)
value = regexprep(char(value), '[\r\n,]+', ' ');
value = strtrim(regexprep(value, '\s+', ' '));
end
