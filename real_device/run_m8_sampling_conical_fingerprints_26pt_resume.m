function result = run_m8_sampling_conical_fingerprints_26pt_resume(previousRunDir)
%RUN_M8_SAMPLING_CONICAL_FINGERPRINTS_26PT_RESUME Continue an incomplete run.
%
% With no input, select the newest resumable M8 campaign.  A supplied parent
% remains supported.  Other tool sizes are excluded by prefix, campaign ID,
% plan hash and active M8 STEP hash before the shared executor validates the
% full immutable lineage.

assert(nargin <= 1, ...
    'M12Demo:SamplingResumePathInput', ...
    'Pass no input for automatic resume, or one previous M8 run directory.');
if nargin == 0 || isempty(previousRunDir)
    previousRunDir = selectLatestResumableM8Campaign();
    fprintf('[M8 AUTO RESUME] Selected parent run:\n  %s\n', ...
        previousRunDir);
end
assert(ischar(previousRunDir) || ...
    (isstring(previousRunDir) && isscalar(previousRunDir)), ...
    'M12Demo:SamplingResumePathInput', ...
    'The previous M8 sampling run directory must be text.');
rehash path;
clear execute_m12_contact_engagement_policy
result = execute_m12_contact_engagement_policy( ...
    'DATASET_M8_CONICAL_FINGERPRINTS_26PT', previousRunDir);
end

function runDir = selectLatestResumableM8Campaign()
entryDir = fileparts(mfilename('fullpath'));
dataRoot = fullfile(entryDir, 'data');
planPath = fullfile(entryDir, 'configs', ...
    'm8_printed_cad_conical_sampling_v2.json');
planSha256 = localSha256(planPath);
expectedPegSha256 = ...
    '22303873354eeb02d82c2492cb3a5d6b8ba73860b31a67804ca501347692f24b';
candidates = dir(fullfile( ...
    dataRoot, 'M8_conical_fingerprints_26pt_*'));
candidates = candidates([candidates.isdir]);
if isempty(candidates)
    error('M12Demo:SamplingResumeAutoSelect', ...
        'No M8 26-point sampling campaign exists under %s.', dataRoot);
end
checkpointTimes = -inf(1, numel(candidates));
for candidateIndex = 1:numel(candidates)
    checkpointInfo = dir(fullfile( ...
        candidates(candidateIndex).folder, ...
        candidates(candidateIndex).name, ...
        'sampling_campaign.json'));
    if ~isempty(checkpointInfo)
        checkpointTimes(candidateIndex) = checkpointInfo(1).datenum;
    end
end
[~, order] = sort(checkpointTimes, 'descend');
candidates = candidates(order);

runDir = '';
for candidateIndex = 1:numel(candidates)
    candidateDir = fullfile( ...
        candidates(candidateIndex).folder, ...
        candidates(candidateIndex).name);
    checkpointPath = fullfile(candidateDir, 'sampling_campaign.json');
    if ~isfile(checkpointPath)
        continue
    end
    try
        campaign = jsondecode(fileread(checkpointPath));
    catch
        continue
    end
    [~, candidateName] = fileparts(candidateDir);
    hashes = struct();
    if isfield(campaign, 'cad_and_configuration_hashes')
        hashes = campaign.cad_and_configuration_hashes;
    end
    if ~isfield(campaign, 'campaign') || ...
            ~strcmp(char(campaign.campaign), ...
                'm8_run_local_conical_fingerprints_26pt_v2') || ...
            ~isfield(campaign, 'run_session_id') || ...
            ~strcmp(char(campaign.run_session_id), candidateName) || ...
            ~isfield(campaign, 'sampling_plan_sha256') || ...
            ~strcmp(char(campaign.sampling_plan_sha256), planSha256) || ...
            ~isfield(hashes, 'active_peg_step_sha256') || ...
            ~strcmp(char(hashes.active_peg_step_sha256), ...
                expectedPegSha256) || ...
            ~isfield(campaign, 'attempt_count_planned') || ...
            double(campaign.attempt_count_planned) ~= 26 || ...
            ~isfield(campaign, 'status') || ...
            ~isResumableCampaignStatus(char(campaign.status)) || ...
            ~isfield(campaign, 'attempts') || ...
            ~hasCompletedCone(campaign.attempts)
        continue
    end
    runDir = candidateDir;
    break
end

if isempty(runDir)
    error('M12Demo:SamplingResumeAutoSelect', ...
        ['No resumable M8 campaign with matching CAD lineage and at least ', ...
         'one completed cone was found under %s.'], dataRoot);
end
end

function eligible = isResumableCampaignStatus(status)
eligible = contains(status, 'ABORTED') || ...
    strcmp(status, 'RUNNING') || ...
    strcmp(status, ...
        'RETURNED_TO_INITIAL_POSE_BUT_CAMPAIGN_FINALIZATION_FAILED');
end

function completed = hasCompletedCone(attempts)
completed = false;
if ~isstruct(attempts) || isempty(attempts)
    return
end
for attemptIndex = 1:numel(attempts)
    if isfield(attempts(attemptIndex), 'cone_completed') && ...
            isscalar(attempts(attemptIndex).cone_completed) && ...
            logical(attempts(attemptIndex).cone_completed)
        completed = true;
        return
    end
end
end

function digest = localSha256(path)
assert(isfile(path), 'M12Demo:SamplingResumePlanMissing', ...
    'M8 sampling plan is missing: %s', path);
assert(~isempty(regexp(path, '^[A-Za-z0-9_./-]+$', 'once')), ...
    'M12Demo:SamplingResumePlanPath', ...
    'Unsupported M8 sampling plan path: %s', path);
[status, output] = system(['/usr/bin/sha256sum ', path]);
assert(status == 0, 'M12Demo:SamplingResumePlanHash', ...
    'Could not hash the M8 sampling plan.');
tokens = regexp(output, '^([0-9a-fA-F]{64})', 'tokens', 'once');
assert(~isempty(tokens), 'M12Demo:SamplingResumePlanHash', ...
    'Unexpected sha256sum output for the M8 sampling plan.');
digest = lower(tokens{1});
end
