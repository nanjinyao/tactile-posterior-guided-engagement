function result = run_m12_paired_full_loop_trial()
%RUN_M12_PAIRED_FULL_LOOP_TRIAL Run one selected paired M12 method immediately.
%
% Place the upright, unloaded M12 tip a little above the approximate hole
% centre and run this file.  There is deliberately no prompt, menu, token or
% method argument.  Edit only selectedMethodIndex below, then run this file.
% The launcher checkpoints one fixed four-method demo but executes only that
% selected method; it never advances into another method automatically.
% The same selected method may be run repeatedly regardless of its prior
% COMPLETE, RUNNING or RETRY_PENDING checkpoint status.  After each trial,
% recover the robot manually to the same above-centre teaching condition and
% run this same file again.
%
% The one offset below is a fixed pseudorandom demo point near the successful
% real M12 clean fingerprint A003p75/r5.669.  It is moved radially inward so
% the common 4.2 mm method reach remains inside the conservative 0.75 mm CAD
% capture radius even with a 0.25 mm touchdown-XY lock error.  The literal is
% shared by all four methods; restarting MATLAB cannot silently redraw it.
% This selector deliberately reuses the V2 checkpoint, fixed centre and
% private-trial records.  Legacy V2 next/pending state is retained as history
% but cannot choose or block the method.  The older 16-trial
% paired_full_loop_campaign.json remains untouched.

% THE ONLY DEMO METHOD SELECTOR -- edit this literal to 1, 2, 3 or 4.
%   1: Proposed+ learned posterior + residual entropy search
%   2: Proposed learned shortcut + local outward spiral
%   3: Improved Direct x3 learned
%   4: Pure outward spiral
selectedMethodIndex = 4;
assert(isnumeric(selectedMethodIndex) && ...
        isscalar(selectedMethodIndex) && ...
        isfinite(selectedMethodIndex) && ...
        selectedMethodIndex == fix(selectedMethodIndex) && ...
        selectedMethodIndex >= 1 && selectedMethodIndex <= 4, ...
    'M12Demo:PairedMethodSelector', ...
    'selectedMethodIndex must be one integer literal from 1 through 4.');

realDir = fileparts(mfilename('fullpath'));
dataDir = fullfile(realDir, 'data');
if ~isfolder(dataDir)
    [made, message] = mkdir(dataDir);
    assert(made, 'M12Demo:PairedCampaignDataDirectory', ...
        'Cannot create %s: %s', dataDir, message);
end
campaignPath = fullfile(dataDir, ...
    'paired_full_loop_demo_campaign_v2.json');

offsetsFixtureMm = [ ...
    4.580702667, 0.420907446];
offsetIndex = 1;
offsetFixtureMm = offsetsFixtureMm(offsetIndex, :);
assert(all(isfinite(offsetFixtureMm)), ...
    'M12Demo:PairedOffsetFinite', ...
    'The fixed paired demo offset is not finite.');
sourceSampleOffsetFixtureMm = [ ...
    5.657069292, 0.370783911];
demoDesignId = ...
    'M12_FIXED_SEED_DEMO_NEAR_CLEAN_A003P75_R4P600_V2';
demoSeedToken = ...
    'M12_DEMO_SEED_20260729_A003P75';
sourceSampleId = ...
    'M12-CLEAN_CANDIDATE-SUPPORTED-A003p75';
demoRadiusMm = 4.600;
demoAngleFixtureDeg = 5.250;
commonMethodReachMm = 4.200;
conservativeCaptureRadiusMm = 0.750;
touchdownXyLockBoundMm = 0.250;
worstCaseCaptureMarginMm = ...
    conservativeCaptureRadiusMm - ...
    (demoRadiusMm + touchdownXyLockBoundMm - commonMethodReachMm);
assert(worstCaseCaptureMarginMm > 0.0, ...
    'M12Demo:PairedDemoReachability', ...
    'The fixed paired demo offset has no worst-case capture margin.');
methodModes = { ...
    'FULL_LOOP_PROPOSED_PLUS_LEARNED_ENTROPY', ...
    'FULL_LOOP_PROPOSED_LEARNED_LOCAL_SPIRAL', ...
    'FULL_LOOP_BASELINE_IMPROVED_DIRECT_X3_LEARNED', ...
    'FULL_LOOP_BASELINE_PURE_OUTWARD_SPIRAL'};
trialCount = numel(methodModes);
assert(trialCount == 4, 'M12Demo:PairedMethodTable', ...
    'The paired demo must retain exactly four methods.');

if isfile(campaignPath)
    campaign = jsondecode(fileread(campaignPath));
    validatePairedCampaign(campaign, offsetsFixtureMm, ...
        methodModes, demoDesignId, ...
        demoSeedToken, sourceSampleId, sourceSampleOffsetFixtureMm, ...
        demoRadiusMm, demoAngleFixtureDeg, ...
        commonMethodReachMm, conservativeCaptureRadiusMm, ...
        touchdownXyLockBoundMm, worstCaseCaptureMarginMm);
    campaign = recoverCampaignCenterFromPrivateRecords( ...
        campaign, dataDir);
else
    campaign = struct();
    campaign.schema = 'M12_PAIRED_FULL_LOOP_DEMO_CAMPAIGN_V2';
    campaign.campaign_id = ['M12_PAIRED_DEMO_', ...
        char(datetime('now', 'Format', 'yyyyMMdd_HHmmss_SSS'))];
    campaign.status = 'ACTIVE';
    campaign.created_local = pairedIsoTimestamp();
    campaign.updated_local = campaign.created_local;
    campaign.offset_distribution = ...
        'ONE_FIXED_SEEDED_POINT_NEAR_SUCCESSFUL_REAL_CLEAN_TRACE_V2';
    campaign.demo_design_id = demoDesignId;
    campaign.demo_seed_token = demoSeedToken;
    campaign.source_sample_id = sourceSampleId;
    campaign.source_sample_offset_fixture_mm = ...
        sourceSampleOffsetFixtureMm;
    campaign.demo_radius_mm = demoRadiusMm;
    campaign.demo_angle_fixture_deg = demoAngleFixtureDeg;
    campaign.common_method_reach_mm = commonMethodReachMm;
    campaign.conservative_capture_radius_mm = ...
        conservativeCaptureRadiusMm;
    campaign.touchdown_xy_lock_bound_mm = touchdownXyLockBoundMm;
    campaign.worst_case_capture_margin_mm = ...
        worstCaseCaptureMarginMm;
    campaign.offsets_fixture_mm = offsetsFixtureMm;
    campaign.method_modes = methodModes;
    campaign.method_order = 1:trialCount;
    campaign.campaign_center_world_xy_mm = [];
    campaign.campaign_center_source_public_trial_token = '';
    campaign.next_trial_index = 1;
    campaign.completed_trial_count = 0;
    campaign.trials = repmat(struct( ...
        'trial_index', 0, ...
        'offset_index', 0, ...
        'order_position', 0, ...
        'method_index', 0, ...
        'method_mode', '', ...
        'status', 'PENDING', ...
        'attempt_count', 0, ...
        'current_public_trial_token', '', ...
        'last_started_local', '', ...
        'last_finished_local', '', ...
        'run_directory', '', ...
        'outcome_kind', 'PENDING', ...
        'last_error_identifier', '', ...
        'last_error_message', ''), trialCount, 1);
    for methodIndex = 1:trialCount
        executionMode = methodModes{methodIndex};
        trialIndex = methodIndex;
        campaign.trials(trialIndex).trial_index = trialIndex;
        campaign.trials(trialIndex).offset_index = offsetIndex;
        campaign.trials(trialIndex).order_position = methodIndex;
        campaign.trials(trialIndex).method_index = methodIndex;
        campaign.trials(trialIndex).method_mode = executionMode;
    end
    writePairedCampaignCheckpoint(campaignPath, campaign);
end

% Direct selector semantics: the V2 status and next_trial_index fields are
% historical checkpoint data only.  They never choose the method and a
% COMPLETE selected slot is intentionally repeatable for rapid debugging.
trialIndex = selectedMethodIndex;
methodIndex = selectedMethodIndex;
trial = campaign.trials(trialIndex);
executionMode = methodModes{methodIndex};
assert(double(trial.offset_index) == offsetIndex && ...
        double(trial.method_index) == methodIndex && ...
        strcmp(char(trial.method_mode), executionMode), ...
    'M12Demo:PairedCampaignMethodDrift', ...
    'Campaign trial %d method no longer matches the fixed table.', ...
    trialIndex);

publicTrialToken = char(java.util.UUID.randomUUID());
privateTrialSpec = struct();
privateTrialSpec.schema = 'M12_PAIRED_FULL_LOOP_PRIVATE_TRIAL_V2';
privateTrialSpec.campaign_id = char(campaign.campaign_id);
privateTrialSpec.trial_index = trialIndex;
privateTrialSpec.offset_index = offsetIndex;
privateTrialSpec.offset_fixture_mm = offsetFixtureMm;
privateTrialSpec.method_index = methodIndex;
privateTrialSpec.method_mode = executionMode;
privateTrialSpec.order_position = double(trial.order_position);
privateTrialSpec.public_trial_token = publicTrialToken;
privateTrialSpec.campaign_center_world_xy_mm = ...
    double(campaign.campaign_center_world_xy_mm);
privateTrialSpec.public_entrypoint = ...
    'run_m12_paired_full_loop_trial';
privateTrialSpec.truth_firewall = ...
    'OFFSET_USED_ONLY_FOR_PRE_TOUCHDOWN_AIR_TRANSPORT_NOT_POLICY_INPUT';
privateTrialSpec.demo_design_id = demoDesignId;
privateTrialSpec.demo_seed_token = demoSeedToken;
privateTrialSpec.source_sample_id = sourceSampleId;

campaign.trials(trialIndex).status = 'RUNNING';
campaign.trials(trialIndex).attempt_count = ...
    double(campaign.trials(trialIndex).attempt_count) + 1;
campaign.trials(trialIndex).current_public_trial_token = publicTrialToken;
campaign.trials(trialIndex).last_started_local = pairedIsoTimestamp();
campaign.trials(trialIndex).last_finished_local = '';
campaign.trials(trialIndex).run_directory = '';
campaign.trials(trialIndex).outcome_kind = 'RUNNING';
campaign.trials(trialIndex).last_error_identifier = '';
campaign.trials(trialIndex).last_error_message = '';
campaign.status = 'ACTIVE';
campaign.completed_trial_count = sum(strcmp( ...
    {campaign.trials.status}, 'COMPLETE'));
campaign.next_trial_index = trialIndex;
campaign.updated_local = pairedIsoTimestamp();
writePairedCampaignCheckpoint(campaignPath, campaign);

fprintf(['\nM12 paired demo selected method %d/4: one fixed offset, ', ...
    '%s; repeat attempt %d.\n', ...
    'No confirmation is required; live preflight and motion begin now.\n'], ...
    methodIndex, executionMode, ...
    double(campaign.trials(trialIndex).attempt_count));
% Consecutive real-robot iterations edit the shared engine in one MATLAB
% session.  Reload that function automatically so F5 never runs a stale
% cached controller and the operator needs no extra command.
clear execute_m12_contact_engagement_policy
try
    result = execute_m12_contact_engagement_policy( ...
        executionMode, privateTrialSpec);
catch trialError
    campaign = readPairedCampaignCheckpoint(campaignPath);
    campaign = adoptCampaignCenterFromPrivateRecord( ...
        campaign, dataDir, publicTrialToken);
    % Direct x3 finite exhaustion returns normally from the controller and
    % never enters this catch.  Every exception here still represents a hard
    % state, stale/unknown feedback, or implementation failure and remains
    % available for immediate same-method debugging/retry.
    campaign.trials(trialIndex).status = 'RETRY_PENDING';
    campaign.trials(trialIndex).outcome_kind = ...
        'HARD_STATE_OR_IMPLEMENTATION_RETRY_REQUIRED';
    campaign.trials(trialIndex).last_finished_local = pairedIsoTimestamp();
    % Selector mode never advances to another method.  This field echoes the
    % one method whose latest attempt was just checkpointed.
    campaign.next_trial_index = trialIndex;
    campaign.trials(trialIndex).last_error_identifier = ...
        char(trialError.identifier);
    campaign.trials(trialIndex).last_error_message = ...
        pairedOneLine(trialError.message);
    campaign.completed_trial_count = sum(strcmp( ...
        {campaign.trials.status}, 'COMPLETE'));
    if campaign.completed_trial_count == numel(campaign.trials)
        campaign.status = 'COMPLETE';
    else
        campaign.status = 'ACTIVE';
    end
    campaign.updated_local = pairedIsoTimestamp();
    writePairedCampaignCheckpoint(campaignPath, campaign);
    rethrow(trialError);
end

campaign = readPairedCampaignCheckpoint(campaignPath);
campaign = adoptCampaignCenterFromPrivateRecord( ...
    campaign, dataDir, publicTrialToken);
campaign.trials(trialIndex).status = 'COMPLETE';
campaign.trials(trialIndex).last_finished_local = pairedIsoTimestamp();
campaign.trials(trialIndex).run_directory = char(result.run_directory);
finiteDirectExhaustion = strcmp(executionMode, ...
    'FULL_LOOP_BASELINE_IMPROVED_DIRECT_X3_LEARNED') && ...
    isfield(result, 'method_execution_completed') && ...
    logical(result.method_execution_completed) && ...
    isfield(result, 'capture_found') && ~logical(result.capture_found);
if finiteDirectExhaustion
    campaign.trials(trialIndex).outcome_kind = ...
        'METHOD_EXHAUSTED_NO_CAPTURE';
else
    campaign.trials(trialIndex).outcome_kind = 'TASK_SUCCESS';
end
campaign.trials(trialIndex).last_error_identifier = '';
campaign.trials(trialIndex).last_error_message = '';
campaign.completed_trial_count = sum(strcmp( ...
    {campaign.trials.status}, 'COMPLETE'));
campaign.next_trial_index = trialIndex;
if campaign.completed_trial_count == numel(campaign.trials)
    campaign.status = 'COMPLETE';
else
    campaign.status = 'ACTIVE';
end
campaign.updated_local = pairedIsoTimestamp();
writePairedCampaignCheckpoint(campaignPath, campaign);
result.paired_campaign_id = char(campaign.campaign_id);
result.paired_trial_index = trialIndex;
result.paired_selected_method_index = selectedMethodIndex;
result.paired_selected_method_mode = executionMode;
result.paired_outcome_kind = ...
    char(campaign.trials(trialIndex).outcome_kind);
result.paired_selected_method_attempt_count = ...
    double(campaign.trials(trialIndex).attempt_count);
result.paired_completed_trial_count = campaign.completed_trial_count;
end

function campaign = recoverCampaignCenterFromPrivateRecords( ...
        campaign, dataDir)
if ~isempty(campaign.campaign_center_world_xy_mm)
    return;
end
for trialIndex = numel(campaign.trials):-1:1
    token = char(campaign.trials( ...
        trialIndex).current_public_trial_token);
    if isempty(token)
        continue;
    end
    campaign = adoptCampaignCenterFromPrivateRecord( ...
        campaign, dataDir, token);
    if ~isempty(campaign.campaign_center_world_xy_mm)
        return;
    end
end
end

function campaign = adoptCampaignCenterFromPrivateRecord( ...
        campaign, dataDir, publicTrialToken)
privatePath = fullfile(dataDir, 'paired_full_loop_private', ...
    [publicTrialToken, '.json']);
if ~isfile(privatePath)
    return;
end
record = jsondecode(fileread(privatePath));
candidate = double(reshape( ...
    record.campaign_center_world_xy_mm, 1, []));
assert(numel(candidate) == 2 && all(isfinite(candidate)), ...
    'M12Demo:PairedCampaignCenterRecord', ...
    'The private paired record contains an invalid campaign centre.');
if isempty(campaign.campaign_center_world_xy_mm)
    campaign.campaign_center_world_xy_mm = candidate;
    campaign.campaign_center_source_public_trial_token = ...
        publicTrialToken;
else
    existing = double(reshape( ...
        campaign.campaign_center_world_xy_mm, 1, []));
    assert(norm(existing - candidate) <= 1e-9, ...
        'M12Demo:PairedCampaignCenterDrift', ...
        'A private trial attempted to change the fixed campaign centre.');
end
end

function validatePairedCampaign( ...
        campaign, offsetsFixtureMm, methodModes, ...
        demoDesignId, demoSeedToken, sourceSampleId, ...
        sourceSampleOffsetFixtureMm, ...
        demoRadiusMm, demoAngleFixtureDeg, commonMethodReachMm, ...
        conservativeCaptureRadiusMm, touchdownXyLockBoundMm, ...
        worstCaseCaptureMarginMm)
assert(isstruct(campaign) && ...
    isfield(campaign, 'schema') && ...
    strcmp(char(campaign.schema), ...
        'M12_PAIRED_FULL_LOOP_DEMO_CAMPAIGN_V2'), ...
    'M12Demo:PairedCampaignSchema', ...
    'The paired full-loop demo checkpoint has an unsupported schema.');
assert(isfield(campaign, 'offsets_fixture_mm') && ...
    isequal(double(reshape( ...
        campaign.offsets_fixture_mm, 1, [])), offsetsFixtureMm) && ...
    isfield(campaign, 'method_order') && ...
    isequal(double(reshape(campaign.method_order, 1, [])), ...
        1:numel(methodModes)), ...
    'M12Demo:PairedCampaignDesignDrift', ...
    'The persisted fixed demo offset/method order changed.');
assert(isfield(campaign, 'demo_design_id') && ...
    strcmp(char(campaign.demo_design_id), demoDesignId) && ...
    isfield(campaign, 'demo_seed_token') && ...
    strcmp(char(campaign.demo_seed_token), demoSeedToken) && ...
    isfield(campaign, 'source_sample_id') && ...
    strcmp(char(campaign.source_sample_id), sourceSampleId) && ...
    isfield(campaign, 'source_sample_offset_fixture_mm') && ...
    isequal(double(reshape( ...
        campaign.source_sample_offset_fixture_mm, 1, [])), ...
        sourceSampleOffsetFixtureMm) && ...
    isfield(campaign, 'demo_radius_mm') && ...
    abs(double(campaign.demo_radius_mm) - demoRadiusMm) <= 1e-12 && ...
    isfield(campaign, 'demo_angle_fixture_deg') && ...
    abs(double(campaign.demo_angle_fixture_deg) - ...
        demoAngleFixtureDeg) <= 1e-12 && ...
    isfield(campaign, 'common_method_reach_mm') && ...
    abs(double(campaign.common_method_reach_mm) - ...
        commonMethodReachMm) <= 1e-12 && ...
    isfield(campaign, 'conservative_capture_radius_mm') && ...
    abs(double(campaign.conservative_capture_radius_mm) - ...
        conservativeCaptureRadiusMm) <= 1e-12 && ...
    isfield(campaign, 'touchdown_xy_lock_bound_mm') && ...
    abs(double(campaign.touchdown_xy_lock_bound_mm) - ...
        touchdownXyLockBoundMm) <= 1e-12 && ...
    isfield(campaign, 'worst_case_capture_margin_mm') && ...
    abs(double(campaign.worst_case_capture_margin_mm) - ...
        worstCaseCaptureMarginMm) <= 1e-12 && ...
    worstCaseCaptureMarginMm > 0.0, ...
    'M12Demo:PairedCampaignProvenanceDrift', ...
    'The persisted fixed demo provenance/reachability contract changed.');
assert(isfield(campaign, 'campaign_center_world_xy_mm') && ...
    (isempty(campaign.campaign_center_world_xy_mm) || ...
     (numel(campaign.campaign_center_world_xy_mm) == 2 && ...
      all(isfinite(double( ...
          campaign.campaign_center_world_xy_mm))))), ...
    'M12Demo:PairedCampaignCenter', ...
    'The persisted fixed campaign centre is invalid.');
persistedModes = cellstr(string(campaign.method_modes));
assert(isequal(reshape(persistedModes, 1, []), methodModes) && ...
    isfield(campaign, 'trials') && ...
    numel(campaign.trials) == numel(methodModes), ...
    'M12Demo:PairedCampaignMethodDrift', ...
    'The persisted paired method table changed.');
for methodIndex = 1:numel(methodModes)
    trial = campaign.trials(methodIndex);
    assert(double(trial.trial_index) == methodIndex && ...
            double(trial.offset_index) == 1 && ...
            double(trial.order_position) == methodIndex && ...
            double(trial.method_index) == methodIndex && ...
            strcmp(char(trial.method_mode), methodModes{methodIndex}), ...
        'M12Demo:PairedCampaignTrialIdentity', ...
        'The persisted V2 slot %d no longer matches method %d.', ...
        methodIndex, methodIndex);
end
end

function campaign = readPairedCampaignCheckpoint(path)
assert(isfile(path), 'M12Demo:PairedCampaignMissing', ...
    'Paired campaign checkpoint disappeared: %s', path);
campaign = jsondecode(fileread(path));
end

function writePairedCampaignCheckpoint(path, campaign)
campaign.updated_local = pairedIsoTimestamp();
encoded = [jsonencode(campaign, 'PrettyPrint', true), newline];
temporaryPath = [tempname(fileparts(path)), '.tmp'];
fileId = fopen(temporaryPath, 'w');
assert(fileId >= 0, 'M12Demo:PairedCampaignWrite', ...
    'Cannot open a temporary paired campaign checkpoint.');
closer = onCleanup(@() fclose(fileId));
fwrite(fileId, encoded, 'char');
clear closer;
[moved, message] = movefile(temporaryPath, path, 'f');
assert(moved, 'M12Demo:PairedCampaignCommit', ...
    'Cannot atomically replace %s: %s', path, message);
end

function value = pairedIsoTimestamp()
value = char(datetime('now', 'TimeZone', 'local', ...
    'Format', 'yyyy-MM-dd''T''HH:mm:ss.SSSXXX'));
end

function value = pairedOneLine(value)
value = regexprep(char(value), '[\r\n,]+', ' ');
value = strtrim(regexprep(value, '\s+', ' '));
end
