        'SELECTED CAD SHORTCUT %.2f mm', norm(data.shortcutTask)));
plot(ax, shortcutUv(1), shortcutUv(2), 's', ...
    'MarkerSize', 7.5, 'MarkerFaceColor', shortcutColor, ...
    'MarkerEdgeColor', 'w', 'HandleVisibility', 'off');

text(ax, 0.015, 0.985, sprintf([ ...
    'LEARNED HOLE DIRECTION\n', ...
    '\\theta = %.1f^\\circ   confidence p_{top} = %.3f   ', ...
    'quality = %.3f   APS = %d'], ...
    data.topDirectionDeg, data.topProbability, ...
    data.sampleQuality, data.apsSize), ...
    'Units', 'normalized', 'HorizontalAlignment', 'left', ...
    'VerticalAlignment', 'top', 'FontWeight', 'bold', ...
    'FontSize', 9.0, 'Color', learnedColor, ...
    'BackgroundColor', [1.00, 0.96, 1.00], ...
    'EdgeColor', learnedColor, 'Margin', 4.0, ...
    'Interpreter', 'tex', 'HandleVisibility', 'off');
