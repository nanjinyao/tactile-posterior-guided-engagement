    names = defaults;
    return;
end
value = output.state_names;
if iscell(value)
    names = cellfun(@printable, value(:).', 'UniformOutput', false);
elseif isstring(value)
    names = cellstr(value(:).');
elseif ischar(value) && size(value, 1) == 3
    names = cellstr(value);
else
    names = defaults;
end
if numel(names) ~= 3
    names = defaults;
end
names = cellfun(@(name) strrep(name, '_', '-'), ...
    names, 'UniformOutput', false);
end

function angles = apsAngles(output, directionAngles)
if isfield(output, 'aps_direction_angles_deg')
    angles = double(output.aps_direction_angles_deg(:));
elseif isfield(output, 'aps_direction_classes')
    indices = round(double(output.aps_direction_classes(:))) + 1;
    indices = indices(indices >= 1 & indices <= numel(directionAngles));
    angles = directionAngles(indices);
else
    angles = zeros(0, 1);
end
angles = mod(angles(isfinite(angles)), 360.0);
end

function values = interpCircularBins(queryAngles, classAngles, probabilities)
queryAngles = mod(double(queryAngles(:)), 360.0);
classAngles = mod(double(classAngles(:)), 360.0);
probabilities = double(probabilities(:));
values = zeros(size(queryAngles));
for index = 1:numel(queryAngles)
    distance = abs(mod(classAngles - queryAngles(index) + ...
        180.0, 360.0) - 180.0);
    [~, nearest] = min(distance);
    values(index) = probabilities(nearest);
end
end

function value = finiteField(container, name, fallback)
value = fallback;
if isstruct(container) && isfield(container, name)
    candidate = double(container.(name));
    if isscalar(candidate) && isfinite(candidate)
        value = candidate;
    end
end
end

function value = fieldOr(container, name, fallback)
value = fallback;
if isstruct(container) && isfield(container, name)
    value = container.(name);
end
end

function value = printable(value)
if isstring(value)
    value = char(value);
elseif isnumeric(value) || islogical(value)
    value = mat2str(value);
elseif iscell(value) && isscalar(value)
    value = printable(value{1});
end
if ~ischar(value)
    value = '<unprintable>';
end
value = strtrim(value);
end

function visible = figureVisibility(cfg)
visible = 'on';
if ~isstruct(cfg) || ~isfield(cfg, 'visualization')
    return;
end
visualization = cfg.visualization;
if isfield(visualization, 'learned_postcone_visible')
    candidate = visualization.learned_postcone_visible;
elseif isfield(visualization, 'visible')
    candidate = visualization.visible;
else
    return;
end
if islogical(candidate) && isscalar(candidate)
    if candidate
        visible = 'on';
    else
        visible = 'off';
    end
elseif ischar(candidate) || (isstring(candidate) && isscalar(candidate))
    candidate = lower(char(candidate));
    if any(strcmp(candidate, {'on', 'off'}))
        visible = candidate;
    end
end
end

function value = logicalScalarField(container, name, fallback)
value = logical(fallback);
if ~isstruct(container) || ~isfield(container, name)
    return;
end
candidate = container.(name);
if islogical(candidate) && isscalar(candidate)
    value = candidate;
end
end
