    'Color', [0.08, 0.08, 0.08], 'LineStyle', '--', ...
    'LineWidth', 1.5, 'MaxHeadSize', 0.30, ...
    'DisplayName', 'circular mean diagnostic', ...
    'HandleVisibility', 'off');

apsHandle = plot(ax, NaN, NaN, 'p', 'LineStyle', 'none', ...
    'Color', [0.58, 0.16, 0.72], 'MarkerFaceColor', ...
    [0.75, 0.48, 0.86], 'MarkerSize', 8.0, ...
    'DisplayName', 'discrete APS');
set(apsHandle, 'DisplayName', sprintf( ...
    'APS DIRECTION SET (n=%d)', data.apsSize));
if ~isempty(data.apsAnglesDeg)
    apsTask = 0.92 * viewRadius * ...
        [cosd(data.apsAnglesDeg), sind(data.apsAnglesDeg)];
    apsUv = taskToDisplay(apsTask);
    set(apsHandle, 'XData', apsUv(:, 1), 'YData', apsUv(:, 2));
