function [polygonTask, axialStartMm] = residualCorridorPolygon( ...
        radiusMm, centreDeg, halfDeg, shortcutTask)
% Display the part of the credible CAD sector that remains after the
% selected shortcut.  This is a visualization of the already-computed
% route/corridor contract, not a new planner or controller input.
radiusMm = double(radiusMm);
centreDeg = double(centreDeg);
halfDeg = min(max(double(halfDeg), 0.0), 89.9);
shortcutTask = double(reshape(shortcutTask, 1, 2));
direction = [cosd(centreDeg), sind(centreDeg)];
lateral = [-direction(2), direction(1)];
axialStartMm = min(max(dot(shortcutTask, direction), 0.0), ...
    radiusMm);
outerAngles = linspace(centreDeg - halfDeg, ...
    centreDeg + halfDeg, 81).';
outerTask = radiusMm * ...
    [cosd(outerAngles), sind(outerAngles)];
chordHalfMm = sqrt(max(0.0, ...
    radiusMm ^ 2 - axialStartMm ^ 2));
wedgeHalfMm = axialStartMm * tand(halfDeg);
innerHalfMm = min(chordHalfMm, wedgeHalfMm);
innerCentre = axialStartMm * direction;
innerLower = innerCentre - innerHalfMm * lateral;
innerUpper = innerCentre + innerHalfMm * lateral;
polygonTask = [innerLower; outerTask; innerUpper];
end

