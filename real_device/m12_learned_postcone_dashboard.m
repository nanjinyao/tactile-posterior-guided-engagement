function dashboard = m12_learned_postcone_dashboard(dashboard, payload)
%M12_LEARNED_POSTCONE_DASHBOARD Deferred learned/CAD decision display.
%
%   dashboard = m12_learned_postcone_dashboard(dashboard, payload)
%
% This function is an observation-only phase-boundary consumer.  The caller
% supplies the already acquired cone, already completed model inference, and
% already computed CAD route in memory.  This function owns no robot or sensor
% interface and does not feed its display-only filtering back into payload,
% inference, posterior construction, or control.
%
% Required payload fields:
%   model_input              Exact seven-channel active-model input.
%   learned_output           48-bin direction and three-state posterior.
%   grid_offsets_world_mm    N-by-2 WORLD offset hypotheses.
%   grid_posterior           N posterior probabilities.
%   shortcut                 Already selected bounded route.
%   corridor                 TOP1-centred credible-sector diagnostics.
%   execution_mode           Active learned method name for an obvious label.
%   direct_servo_active      Must be false at this deferred phase boundary.
%   cfg                      Active controller configuration.
%   attempt_label            Human-readable attempt identifier.
%
% The seven phase plots show the exact physical 360-bin sequence before
% per-seed normalization.  Circular Fourier curves and the robust residual
% band are DISPLAY ONLY / NOT MODEL CI.

narginchk(2, 2);
assert(isstruct(payload) && isscalar(payload), ...
    'M12LearnedDashboard:PayloadType', ...
    'payload must be a scalar struct.');
required = {'model_input', 'learned_output', ...
    'grid_offsets_world_mm', 'grid_posterior', 'shortcut', ...
    'corridor', 'execution_mode', 'direct_servo_active', ...
    'cfg', 'attempt_label'};
assert(all(cellfun(@(name) isfield(payload, name), required)), ...
    'M12LearnedDashboard:PayloadFields', ...
    'The learned post-cone payload is incomplete.');
assert(islogical(payload.direct_servo_active) && ...
        isscalar(payload.direct_servo_active) && ...
        ~payload.direct_servo_active, ...
    'M12LearnedDashboard:DirectServoState', ...
    ['The learned post-cone dashboard may refresh only after DirectServo ', ...
     'has completely stopped.']);

data = prepareDisplayData(payload);
[figureHandle, updateCount] = reusableFigure(dashboard, payload);
clf(figureHandle);
set(figureHandle, 'Color', 'w', ...
    'Name', 'M12 learned post-cone decision', ...
    'NumberTitle', 'off', ...
    'Visible', figureVisibility(payload.cfg));

topAxes = axes('Parent', figureHandle, ...
    'Position', [0.045, 0.10, 0.43, 0.82]);
renderTopView(topAxes, data);

sequenceAxes = renderSequencePanel(figureHandle, data);
[posteriorAxes, stateAxes, informationHandle] = ...
    renderDecisionPanel(figureHandle, data);

% Two short lines at a reduced size.  As one line this banner is far wider
% than the figure, so it overflowed the canvas and collided with the panel
% titles underneath it in every 2026-07-29 screenshot.
sgtitle(figureHandle, { ...
    sprintf('M12 learned post-cone decision  |  %s', ...
        printable(payload.execution_mode)), ...
    sprintf('%s  |  DEFERRED DISPLAY ONLY / NO CONTROL FEEDBACK', ...
        printable(payload.attempt_label))}, ...
    'FontWeight', 'bold', 'FontSize', 9, 'Interpreter', 'none');

refresh = presentCompletedPhaseBoundaryFigure(figureHandle, payload.cfg);
dashboard = struct( ...
    'enabled', true, ...
    'failure', '', ...
    'figure', figureHandle, ...
    'top_axes', topAxes, ...
    'sequence_axes', sequenceAxes, ...
    'posterior_axes', posteriorAxes, ...
    'state_axes', stateAxes, ...
    'information_text', informationHandle, ...
    'last_attempt_label', printable(payload.attempt_label), ...
    'last_execution_mode', printable(payload.execution_mode), ...
    'last_model_id', data.modelId, ...
    'update_count', updateCount + 1, ...
    'phase_boundary_refresh', refresh, ...
    'render_contract', ...
        ['POST_DIRECTSERVO_VISIBLE_FRONT_SINGLE_DRAWNOW_', ...
         'IN_MEMORY_DISPLAY_ONLY_NOT_MODEL_CI']);
end

function refresh = presentCompletedPhaseBoundaryFigure(figureHandle, cfg)
% All expensive plotting above is complete and DirectServo is already stopped.
% Select the docked figure/tab and flush exactly once so the learned decision is
% visible before the next blocking KST endpoint call.  This helper owns no
% robot/sensor handle and is never called from the 40 Hz command loop.
% These three flags used to be welded together by one assert, so none of them
% could be used to mitigate anything.  They are now honoured independently,
% because on 2026-07-30 this presenter intermittently blocked forever: renders
% that succeed report 0.000-1.000 s, but four trials hung here for 30 s until
% the operator interrupted, with no window ever shown.
%
% figure(figureHandle) is the prime suspect and is now opt-in.  Raising and
% focusing a window goes through the X11 window manager, which can block
% indefinitely, and unlike the drawnow below it was never even timed -- the
% clock starts after it.  It is also purely cosmetic: the window still appears
% from the Visible flag, it simply may not jump in front of the IDE.  Losing
% that is worth far more than losing a real-robot trial to a deadlock.
visualization = cfg.visualization;
assert(logicalScalarField( ...
        visualization, 'learned_postcone_visible', false), ...
    'M12LearnedDashboard:PhaseBoundaryPresentationDisabled', ...
    'Post-cone visualization requires the visible flag to be enabled.');
bringToFront = logicalScalarField( ...
    visualization, 'learned_postcone_bring_to_front', false);
flushOnce = logicalScalarField(visualization, ...
    'learned_postcone_single_phase_boundary_drawnow', false);
set(figureHandle, 'Visible', 'on');
if bringToFront
    figure(figureHandle);
end
refreshClock = tic;
drawnowCount = 0;
if flushOnce
    drawnow limitrate nocallbacks;
    drawnowCount = 1;
end
refresh = struct( ...
    'visible', true, ...
    'brought_to_front', bringToFront, ...
    'drawnow_count', drawnowCount, ...
    'elapsed_s', toc(refreshClock), ...
    'stage', 'AFTER_DIRECTSERVO_STOP_BEFORE_BLOCKING_SEARCH');
end

function [figureHandle, updateCount] = reusableFigure(dashboard, payload)
updateCount = 0;
if isempty(dashboard)
    figureHandle = figure('Visible', figureVisibility(payload.cfg));
    return;
end
assert(isstruct(dashboard) && isscalar(dashboard), ...
    'M12LearnedDashboard:DashboardType', ...
    'dashboard must be empty or a scalar struct.');
if isfield(dashboard, 'update_count') && ...
        isfinite(double(dashboard.update_count))
    updateCount = double(dashboard.update_count);
end
if isfield(dashboard, 'enabled') && logical(dashboard.enabled)
    assert(isfield(dashboard, 'figure') && ...
            isgraphics(dashboard.figure, 'figure'), ...
        'M12LearnedDashboard:FigureClosed', ...
        'The learned post-cone window was closed.');
    figureHandle = dashboard.figure;
    return;
end
failure = char(fieldOr(dashboard, 'failure', ''));
initialPlaceholder = isempty(failure) || ...
    startsWith(failure, 'NOT_RENDERED') || ...
    startsWith(failure, 'NOT_INITIALIZED');
assert(initialPlaceholder, 'M12LearnedDashboard:Disabled', ...
    'The learned post-cone display is disabled: %s', failure);
% Close this display's own figures from earlier runs in the same MATLAB
% session before opening another one.  Consecutive real-robot trials never
% close their windows, and the single phase-boundary drawnow below has to
% repaint every open figure: after six trials on 2026-07-30 that wedged the
% frontend, the render never returned, and the trial had to be interrupted
% by hand with no window ever shown.  Only figures this file tagged are
% touched, so an operator's own plots survive.
delete(findall(groot, 'Type', 'figure', ...
    'Tag', 'M12_LEARNED_POSTCONE_DECISION'));
figureHandle = figure('Visible', figureVisibility(payload.cfg), ...
    'Tag', 'M12_LEARNED_POSTCONE_DECISION');
end

function data = prepareDisplayData(payload)
cfg = payload.cfg;
assert(isstruct(cfg) && isfield(cfg, 'frame') && ...
        isfield(cfg.frame, 'world_from_fixture_rotation') && ...
        isfield(cfg, 'search') && isfield(cfg, 'learning'), ...
    'M12LearnedDashboard:Configuration', ...
    'cfg lacks the active frame/search/learning contract.');
worldFromTask = double(cfg.frame.world_from_fixture_rotation);
assert(isequal(size(worldFromTask), [3, 3]) && ...
        all(isfinite(worldFromTask), 'all'), ...
    'M12LearnedDashboard:Frame', ...
    'WORLD<-fixture rotation is invalid.');

modelInput = payload.model_input;
inputFields = {'phase_rad', 'model_fx_n', 'model_fy_n', ...
    'model_fz_n', 'model_tx_nm', 'model_ty_nm', 'model_tz_nm', ...
    'model_cmd_z_relative_mm'};
assert(isstruct(modelInput) && ...
        all(cellfun(@(name) isfield(modelInput, name), inputFields)), ...
    'M12LearnedDashboard:ModelInput', ...
    'The exact active-model input is incomplete.');
if isfield(modelInput, 'world_from_task_xy')
    inputFrame = double(modelInput.world_from_task_xy);
    expectedInputFrame = worldFromTask(:, 1:2);
    assert(isequal(size(inputFrame), [3, 2]) && ...
            max(abs(inputFrame(:) - ...
                expectedInputFrame(:))) <= 1e-6, ...
        'M12LearnedDashboard:FrameMismatch', ...
        'Displayed cfg frame differs from the frame used by model input.');
end
[phaseRad, sequence] = exactPhysicalPhaseGrid(modelInput);
[reconstruction, bandLow, bandHigh] = ...
    displayOnlyFourier(sequence, phaseRad);

output = payload.learned_output;
outputFields = {'direction_probabilities', ...
    'direction_class_angles_deg', 'state_probabilities', ...
    'top_direction_deg', 'circular_mean_direction_deg'};
assert(isstruct(output) && ...
        all(cellfun(@(name) isfield(output, name), outputFields)), ...
    'M12LearnedDashboard:LearnedOutput', ...
    'The learned output lacks direction/state posterior fields.');
directionProbability = double(output.direction_probabilities(:));
directionAnglesDeg = double(output.direction_class_angles_deg(:));
stateProbability = double(output.state_probabilities(:));
assert(numel(directionProbability) == 48 && ...
        numel(directionAnglesDeg) == 48 && ...
        numel(stateProbability) == 3 && ...
        all(isfinite(directionProbability)) && ...
        all(directionProbability >= 0.0) && ...
        sum(directionProbability) > 0.0 && ...
        all(isfinite(directionAnglesDeg)) && ...
        all(isfinite(stateProbability)) && ...
        all(stateProbability >= 0.0) && sum(stateProbability) > 0.0, ...
    'M12LearnedDashboard:Posterior', ...
    'Direction/state posterior is invalid.');
directionProbability = directionProbability / sum(directionProbability);
stateProbability = stateProbability / sum(stateProbability);

gridWorld = double(payload.grid_offsets_world_mm);
gridProbability = double(payload.grid_posterior(:));
assert(size(gridWorld, 2) == 2 && ...
        size(gridWorld, 1) == numel(gridProbability) && ...
        all(isfinite(gridWorld), 'all') && ...
        all(isfinite(gridProbability)) && ...
        all(gridProbability >= 0.0) && sum(gridProbability) > 0.0, ...
    'M12LearnedDashboard:GridPosterior', ...
    'Grid hypotheses/posterior are invalid.');
gridProbability = gridProbability / sum(gridProbability);
gridTask = worldVectorsToTask(gridWorld, worldFromTask);

shortcut = payload.shortcut;
assert(isstruct(shortcut) && isfield(shortcut, 'offset_mm'), ...
    'M12LearnedDashboard:Shortcut', ...
    'The selected shortcut lacks offset_mm.');
shortcutWorld = double(reshape(shortcut.offset_mm, 1, []));
assert(numel(shortcutWorld) == 2 && all(isfinite(shortcutWorld)), ...
    'M12LearnedDashboard:Shortcut', ...
    'The selected shortcut offset is invalid.');
shortcutTask = worldVectorsToTask(shortcutWorld, worldFromTask);

% Wrap the three labels in one scalar cell so MATLAB's struct constructor
% does not expand data into a 1-by-3 struct array.
data = struct( ...
    'payload', payload, ...
    'worldFromTask', worldFromTask, ...
    'frameYawDeg', atan2d(worldFromTask(2, 1), worldFromTask(1, 1)), ...
    'phaseRad', phaseRad, ...
    'sequence', sequence, ...
    'reconstruction', reconstruction, ...
    'bandLow', bandLow, ...
    'bandHigh', bandHigh, ...
    'directionProbability', directionProbability, ...
    'directionAnglesDeg', directionAnglesDeg, ...
    'stateProbability', stateProbability, ...
    'stateNames', {stateNames(output)}, ...
    'topDirectionDeg', double(output.top_direction_deg), ...
    'meanDirectionDeg', double(output.circular_mean_direction_deg), ...
    'apsAnglesDeg', apsAngles(output, directionAnglesDeg), ...
    'apsSize', round(finiteField(output, 'aps_set_size', ...
        numel(apsAngles(output, directionAnglesDeg)))), ...
    'topProbability', finiteField(output, 'max_probability', ...
        max(directionProbability)), ...
    'directionEntropyNats', finiteField(output, ...
        'direction_entropy_nats', NaN), ...
    'sampleQuality', finiteField(output, 'sample_quality', NaN), ...
    'gridTask', gridTask, ...
    'gridProbability', gridProbability, ...
    'shortcutWorld', shortcutWorld, ...
    'shortcutTask', shortcutTask, ...
    'executionMode', printable(payload.execution_mode), ...
    'modelId', printable(fieldOr(output, 'model_id', 'unknown-model')));
end

function [phaseGrid, sequence] = exactPhysicalPhaseGrid(modelInput)
phase = mod(double(modelInput.phase_rad(:)), 2.0 * pi);
sequence = [ ...
    double(modelInput.model_fx_n(:)), ...
    double(modelInput.model_fy_n(:)), ...
    double(modelInput.model_fz_n(:)), ...
    double(modelInput.model_tx_nm(:)), ...
    double(modelInput.model_ty_nm(:)), ...
    double(modelInput.model_tz_nm(:)), ...
    double(modelInput.model_cmd_z_relative_mm(:))];
assert(size(sequence, 1) == numel(phase), ...
    'M12LearnedDashboard:InputLength', ...
    'Phase and model-input channel lengths differ.');
finiteRows = isfinite(phase) & all(isfinite(sequence), 2);
phase = phase(finiteRows);
sequence = sequence(finiteRows, :);
assert(numel(phase) >= 32, 'M12LearnedDashboard:FiniteInput', ...
    'Fewer than 32 finite phase samples remain.');
[phase, order] = sort(phase);
sequence = sequence(order, :);
[phase, uniqueIndex] = unique(phase, 'stable');
sequence = sequence(uniqueIndex, :);
assert(numel(phase) >= 32, 'M12LearnedDashboard:UniqueInput', ...
    'Fewer than 32 unique phase samples remain.');
phaseGrid = (0:359).' * (2.0 * pi / 360.0);
phaseExtended = [phase(end) - 2.0 * pi; phase; ...
    phase(1) + 2.0 * pi];
sequenceExtended = [sequence(end, :); sequence; sequence(1, :)];
sequence = interp1(phaseExtended, sequenceExtended, ...
    phaseGrid, 'linear');
% Runtime training contract re-references commanded Z to phase bin zero.
sequence(:, 7) = sequence(:, 7) - sequence(1, 7);
end

function [reconstruction, bandLow, bandHigh] = ...
        displayOnlyFourier(sequence, phase)
sampleCount = size(sequence, 1);
channelCount = size(sequence, 2);
reconstruction = zeros(sampleCount, channelCount, 6);
for order = 1:6
    basis = ones(sampleCount, 1);
    for harmonic = 1:order
        basis = [basis, cos(harmonic * phase), ... %#ok<AGROW>
            sin(harmonic * phase)]; %#ok<AGROW>
    end
    reconstruction(:, :, order) = basis * (basis \ sequence);
end
residual = sequence - reconstruction(:, :, 6);
residualMedian = median(residual, 1);
residualMad = 1.4826 * median( ...
    abs(residual - residualMedian), 1);
bandLow = reconstruction(:, :, 6) + residualMedian - ...
    2.5 * residualMad;
bandHigh = reconstruction(:, :, 6) + residualMedian + ...
    2.5 * residualMad;
end

function renderTopView(ax, data)
hold(ax, 'on');
grid(ax, 'on');
box(ax, 'on');
axis(ax, 'equal');
learnedColor = [0.76, 0.02, 0.66];
shortcutColor = [0.98, 0.39, 0.03];
corridorColor = [0.05, 0.48, 0.92];
cfg = data.payload.cfg;
searchRadius = finiteField(cfg.search, 'grid_radius_mm', ...
    max(vecnorm(data.gridTask, 2, 2)));
captureRadius = finiteField(cfg.search, ...
    'bayes_capture_radius_mm', 0.75);
shortcutCap = finiteField(cfg.search, 'shortcut_cap_mm', ...
    max(norm(data.shortcutTask), searchRadius));
fullSupportRadius = finiteField(cfg.learning, ...
    'm12_head_radius_mm', NaN) - ...
    finiteField(cfg.learning, 'm12_bit_radius_mm', NaN);
headRadius = finiteField(cfg.learning, ...
    'm12_head_radius_mm', 21.275 / 2.0);
mouthAf = finiteField(cfg.search, ...
    'cad_socket_mouth_af_mm', 13.0);
wallAf = finiteField(cfg.search, ...
    'cad_socket_wall_af_mm', 10.6);
tipAf = finiteField(cfg.search, ...
    'cad_tip_face_af_mm', 8.0);
[~, mapIndex] = max(data.gridProbability);
mapTask = data.gridTask(mapIndex, :);
baseRadius = max([searchRadius, captureRadius, shortcutCap, ...
    headRadius + norm(mapTask), ...
    mouthAf / sqrt(3.0) + norm(mapTask), ...
    wallAf / sqrt(3.0) + norm(mapTask), ...
    tipAf / sqrt(3.0), max(vecnorm(data.gridTask, 2, 2)), ...
    norm(data.shortcutTask), 1.0]);
if isfinite(fullSupportRadius) && fullSupportRadius <= 2.0 * baseRadius
    baseRadius = max(baseRadius, fullSupportRadius);
end
viewRadius = 1.08 * baseRadius;

[corridorCentre, corridorHalf, containedMass] = ...
    corridorGeometry(data.payload.corridor, data.topDirectionDeg);
[corridorTask, corridorStartMm] = residualCorridorPolygon( ...
    searchRadius, corridorCentre, corridorHalf, data.shortcutTask);
corridorUv = taskToDisplay(corridorTask);
if isfinite(containedMass) && containedMass < 0.80 - 1e-12
    corridorColor = [0.84, 0.23, 0.18];
end
corridorHandle = patch(ax, corridorUv(:, 1), ...
    corridorUv(:, 2), corridorColor, ...
    'FaceAlpha', 0.18, 'EdgeColor', corridorColor, ...
    'LineWidth', 1.8, 'DisplayName', sprintf( ...
        'CAD-BOUNDED RESIDUAL CORRIDOR %.1f deg', ...
        2.0 * corridorHalf));
corridorDirection = [cosd(corridorCentre), sind(corridorCentre)];
corridorAxisTask = [corridorStartMm; searchRadius] * ...
    corridorDirection;
corridorAxisUv = taskToDisplay(corridorAxisTask);
plot(ax, corridorAxisUv(:, 1), corridorAxisUv(:, 2), '--', ...
    'Color', corridorColor, 'LineWidth', 1.5, ...
    'HandleVisibility', 'off');

headHandle = plotCircleAt(ax, mapTask, headRadius, ...
    [0.28, 0.32, 0.38], '-', 1.3, ...
    sprintf('MAP-centred head D %.3f', 2.0 * headRadius));
mouthHandle = plotHexagonAt(ax, mapTask, mouthAf, ...
    [0.78, 0.10, 0.25], '-', 1.4, ...
    sprintf('MAP mouth AF %.2f', mouthAf));
wallHandle = plotHexagonAt(ax, mapTask, wallAf, ...
    [0.55, 0.05, 0.16], '--', 1.1, ...
    sprintf('MAP deep wall AF %.2f', wallAf));
tipHandle = plotHexagon(ax, tipAf, [0.03, 0.03, 0.03], ...
    '-', 1.8, sprintf('touchdown peg tip AF %.2f', tipAf));
searchHandle = plotCircle(ax, searchRadius, [0.35, 0.38, 0.43], ...
    ':', 1.2, sprintf('CAD search R %.2f', searchRadius));
captureHandle = plotCircle(ax, captureRadius, [0.10, 0.60, 0.25], ...
    '--', 1.5, sprintf('capture R %.2f', captureRadius));
capHandle = plotCircle(ax, shortcutCap, [0.92, 0.48, 0.08], ...
    ':', 1.0, sprintf('shortcut cap R %.2f', shortcutCap));
set([searchHandle, captureHandle, capHandle], ...
    'HandleVisibility', 'off');
if isfinite(fullSupportRadius) && fullSupportRadius > 0.0 && ...
        fullSupportRadius <= viewRadius
    fullSupportHandle = plotCircle(ax, fullSupportRadius, ...
        [0.55, 0.20, 0.68], ...
        '-.', 1.0, sprintf('CAD supported R %.2f', fullSupportRadius));
    set(fullSupportHandle, 'HandleVisibility', 'off');
end

gridUv = taskToDisplay(data.gridTask);
[~, order] = sort(data.gridProbability, 'ascend');
maximumProbability = max(data.gridProbability);
gridHandle = scatter(ax, gridUv(order, 1), gridUv(order, 2), ...
    24.0 + 130.0 * sqrt(data.gridProbability(order) / ...
    maximumProbability), data.gridProbability(order), 'filled', ...
    'MarkerEdgeColor', [0.15, 0.15, 0.15], ...
    'LineWidth', 0.35, 'DisplayName', 'CAD grid posterior');
colormap(ax, parula(256));
mapUv = taskToDisplay(mapTask);
mapHandle = plot(ax, mapUv(1), mapUv(2), 'kx', ...
    'MarkerSize', 10.0, 'LineWidth', 1.8, ...
    'DisplayName', 'MAP hole-centre hypothesis');

probabilityRadius = 0.70 * viewRadius + ...
    0.16 * viewRadius * ...
    data.directionProbability / max(data.directionProbability);
probabilityTask = probabilityRadius .* ...
    [cosd(data.directionAnglesDeg), sind(data.directionAnglesDeg)];
probabilityUv = taskToDisplay(probabilityTask);
scatter(ax, probabilityUv(:, 1), probabilityUv(:, 2), ...
    12.0 + 55.0 * data.directionProbability / ...
    max(data.directionProbability), data.directionProbability, ...
    'filled', 'MarkerEdgeColor', 'none', ...
    'HandleVisibility', 'off');

arrowRadius = 0.70 * viewRadius;
topUv = taskToDisplay(arrowRadius * ...
    [cosd(data.topDirectionDeg), sind(data.topDirectionDeg)]);
topHandle = quiver(ax, 0.0, 0.0, topUv(1), topUv(2), 0.0, ...
    'Color', learnedColor, 'LineWidth', 4.2, ...
    'MaxHeadSize', 0.38, 'DisplayName', sprintf( ...
        'LEARNED HOLE DIRECTION %.1f deg', data.topDirectionDeg));
