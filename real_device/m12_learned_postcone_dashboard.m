    'EdgeColor', shortcutColor, 'Margin', 2.0, ...
    'Interpreter', 'tex', 'HandleVisibility', 'off');

xlim(ax, viewRadius * [-1.0, 1.0]);
ylim(ax, viewRadius * [-1.0, 1.0]);
xlabel(ax, 'display u [mm] = -x_F');
ylabel(ax, 'display v_{up} [mm] = -y_F');
title(ax, sprintf([ ...
    'Task-frame CAD decision | WORLD<-fixture yaw %.2f deg\n', ...
    ['socket CAD is centred at the MAP hole hypothesis; peg tip is ', ...
     'at touchdown origin; +X_F left, +Y_F down']], ...
